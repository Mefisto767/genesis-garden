/**
 * Выбирает следующую подсказку для показа — первый ключ из `candidates`
 * (уже упорядоченный вызывающей стороной по приоритету момента), которого
 * ещё нет в `alreadyShown`. `null`, если ничего нового показывать не нужно.
 * Максимум одна активная подсказка обеспечивается тем, что вызывающая
 * сторона (React-компонент) держит ровно одно состояние "текущая подсказка"
 * и вызывает эту функцию только когда оно пусто — сама функция ничего не
 * знает про "уже показанную сейчас" подсказку, только про персистентную
 * историю (once-per-event, не про конкурентную очередь).
 */
export function nextLumiHintV2(
  candidates: readonly LumiHintKeyV2[],
  alreadyShown: readonly string[]
): LumiHintKeyV2 | null {
  const shown = new Set(alreadyShown);
  for (const key of candidates) {
    if (!shown.has(key)) return key;
  }
  return null;
}
