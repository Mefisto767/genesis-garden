// Детерминированный PRNG (mulberry32) — единственный источник случайности,
// который должны использовать генетика/экономика игры. Позволяет писать
// воспроизводимые unit-тесты (seed -> одна и та же последовательность) и
// в будущем прокидывается с сервера один в один тем же алгоритмом, чтобы
// клиент и сервер могли проверять друг друга при необходимости.
export type RngFn = () => number;

export function mulberry32(seed: number): RngFn {
  let a = seed >>> 0;
  return function rng() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** RNG на бой по умолчанию — обычный Math.random, обёрнутый в тот же тип. */
export const defaultRng: RngFn = () => Math.random();
