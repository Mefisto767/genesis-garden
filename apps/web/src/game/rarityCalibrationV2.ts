function randomAllelePairV2<K extends GenomeV2LocusKey>(locus: K, rng: RngFn): AllelePair<string> {
  const pool = ALLELE_OCCURRENCE_WEIGHTS_V2[locus];
  return {
    a: weightedPick(pool, rng),
    b: weightedPick(pool, rng),
  };
}

/** One randomly generated base genome (contract §4.5.7 point 1) — every
 * locus drawn independently from its occurrence-weight pool, `mutationId`
 * always `null` (a base genome is not itself a mutation result). */
function generateBaseGenomeV2(speciesId: number, rng: RngFn): GenomeV2 {
  return {
    stemForm: randomAllelePairV2('stemForm', rng),
    leafForm: randomAllelePairV2('leafForm', rng),
    flowerForm: randomAllelePairV2('flowerForm', rng),
    primaryColor: randomAllelePairV2('primaryColor', rng),
    secondaryColor: randomAllelePairV2('secondaryColor', rng),
    leafColor: randomAllelePairV2('leafColor', rng),
    pattern: randomAllelePairV2('pattern', rng),
    size: randomAllelePairV2('size', rng),
    aura: randomAllelePairV2('aura', rng),
    speciesId,
    mutationId: null,
  } as GenomeV2;
}

/** Picks two DISTINCT random indices into `population` — retries on a
 * collision rather than allowing self-breeding, matching the real game's
 * `breedNurseryV2` `same_parent` guard (contract §4.8.7/§4.9.2). Bounded
 * retry: population size is always >= 4000, so collision probability per
 * draw is <= 1/4000 and an unbounded loop is not a realistic concern, but a
 * hard cap keeps this defensive rather than truly unbounded. */
function pickDistinctPairIndices(populationSize: number, rng: RngFn): [number, number] {
  const a = Math.floor(rng() * populationSize);
  for (let attempt = 0; attempt < 50; attempt++) {
    const b = Math.floor(rng() * populationSize);
    if (b !== a) return [a, b];
  }
  // Astronomically unlikely with populationSize >= 4000 — last resort.
  return [a, (a + 1) % populationSize];
}

export interface RarityCalibrationResult {
  readonly counts: Record<RarityTierV2, number>;
  readonly total: number;
  readonly populationSize: number;
  readonly finalPityCounter: number;
}

function emptyCounts(): Record<RarityTierV2, number> {
  return { Common: 0, Uncommon: 0, Rare: 0, Epic: 0, Legendary: 0, Mythic: 0 };
}

/**
 * Builds the representative burn-in population (contract §4.5.7 point 1) and
 * returns it together with the RNG/pity state at the moment burn-in ends, so
 * the caller can continue the SAME continuous pity counter into measurement
 * (contract §4.5.7 point 2 — "один непрерывный pityCounter через весь
 * прогон"). None of the burn-in breed results are inspected or counted —
 * only the resulting genomes matter, to grow population diversity (including
 * genomes that carry `aura_radiant` via real mutation, exactly like a real
 * player's collection would after repeated breeding).
 */
function buildRepresentativePopulationV2(rng: RngFn): { population: GenomeV2[]; pityCounter: number } {
  const population: GenomeV2[] = [];
  for (let i = 0; i < BASE_POPULATION_SIZE; i++) {
    // Even index -> species 1, odd index -> species 2: an exact 50/50 split,
    // not a probabilistic one, so "population contains species 1 and 2" is
    // guaranteed by construction (owner requirement), not a matter of luck.
    const speciesId = i % 2 === 0 ? 1 : 2;
    population.push(generateBaseGenomeV2(speciesId, rng));
  }

  let pityCounter = 0;
  for (let gen = 0; gen < BURN_IN_GENERATIONS; gen++) {
    const currentSize = population.length;
    for (let i = 0; i < BURN_IN_BREEDS_PER_GENERATION; i++) {
      const [a, b] = pickDistinctPairIndices(currentSize, rng);
      const result = breedV2(population[a], population[b], pityCounter, rng);
      if (result.ok) {
        pityCounter = result.nextPityCounter;
        population.push(result.genomeV2);
      }
      // A rejected breed cannot happen here (both parents are always species
      // 1/2), and per contract a rejection would leave pityCounter untouched
      // anyway — nothing to do on the `!result.ok` branch.
    }
  }

  return { population, pityCounter };
}

/**
 * Runs the full Slice 13 calibration simulation end to end (contract
 * §4.5.7): builds the burn-in population, then measures EXACTLY
 * `measuredCount` successful `breedV2` results drawn from it, counting each
 * of the six Gate 1 rarity tiers. Pure function of `seed` — no wall-clock, no
 * hidden state, safe to call repeatedly and compare byte-for-byte.
 */
export function runRarityCalibrationSimulationV2(
  seed: number = RARITY_CALIBRATION_SEED,
  measuredCount: number = RARITY_CALIBRATION_MEASURED_COUNT
): RarityCalibrationResult {
  const rng = mulberry32(seed);
  const { population, pityCounter: pityAfterBurnIn } = buildRepresentativePopulationV2(rng);

  const counts = emptyCounts();
  let pityCounter = pityAfterBurnIn;
  let measured = 0;
  while (measured < measuredCount) {
    const [a, b] = pickDistinctPairIndices(population.length, rng);
    const result = breedV2(population[a], population[b], pityCounter, rng);
    if (!result.ok) continue; // Cannot happen for a species-1/2-only population; defensive only.
    pityCounter = result.nextPityCounter;
    counts[result.rarity] += 1;
    measured += 1;
  }

  return { counts, total: measured, populationSize: population.length, finalPityCounter: pityCounter };
}
