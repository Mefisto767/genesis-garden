// Genetics V2 — Slice 13: rarity calibration simulation harness.
//
// Implements docs/GENETICS_GATE1_IMPLEMENTATION_CONTRACT.md §4.5.7 exactly —
// this file is the REAL (non-docs-only) successor to the Python simulation
// described in §4.5.5. It is a test-support module, not game runtime code:
// nothing under `overhaul/`, `ClassicApp.tsx`, `store.ts` or any UI component
// imports it, and it is excluded from the production bundle the same way any
// other unreferenced module is (tree-shaking, not a special case). It exists
// so `rarityCalibrationV2.test.ts` can exercise the REAL `breedV2` (Slice 4),
// the REAL `rarityOfV2` (Slice 3) and a REAL `mulberry32` RNG stream against a
// large, diverse, reproducible population — not a single fixed parent pair.
//
// Methodology (contract §4.5.7, fixed BEFORE any production constant in this
// package was touched by Slice 13 — see docs commit `docs(genetics): lock
// final Gate 1 calibration and regression`):
//
//   1. Population generation (burn-in, NOT part of the measured sample):
//      4000 base genomes, generated by weighted-random allele draw per locus
//      (ALLELE_OCCURRENCE_WEIGHTS_V2 below — the "occurrence weight" column
//      already documented in contract §4.2, encoded here for the first time
//      because nothing in game code needed it before this harness; weight-0
//      alleles, i.e. `aura_radiant`, the sole Gate 1 mutation-pool allele,
//      are excluded from the base draw pool — same rule contract §4.2 already
//      states for the docs-only simulation), split evenly species 1/species 2
//      by index parity (exactly 2000/2000 — deterministic, not a coin flip,
//      so "population contains species 1 and 2" is guaranteed, not merely
//      likely). Then three generations of 2000 intra-population breeds each
//      (random pairs drawn from the CURRENT population at that generation,
//      appended, never replacing — population grows 4000 -> 6000 -> 8000 ->
//      10000), using the REAL `breedV2` so later generations can carry
//      mutation-pool alleles (`aura_radiant`) exactly the way real players'
//      collections would after repeated breeding. None of these 6000 breed
//      results are counted toward the measured sample.
//   2. Measurement: exactly 100000 successful `breedV2` calls, each on a
//      freshly drawn random pair of two DISTINCT genomes from the final
//      10000-genome population (with replacement across draws — the pool
//      itself does not shrink, matching a stable collection being re-bred
//      many times). `pityCounter` is threaded as ONE continuous counter
//      across the ENTIRE run (burn-in AND measurement, one unbroken
//      sequence) — contract §4.5.7 point 2, matching the already-documented
//      §4.5.5 phrasing "непрерывный pityCounter через всю серию" applied
//      literally to the one RNG stream this harness drives from a single
//      seed. Species 1/2 pairs never fail `breedV2`'s species validation, so
//      every one of the 100000 draws is expected to succeed; the loop below
//      still defensively retries on a hypothetical failure rather than
//      assuming it, so "exactly 100000 successful results" is enforced by
//      construction, not by assumption.
//
// Byte-reproducible: one fixed numeric seed (RARITY_CALIBRATION_SEED) feeds
// one `mulberry32` stream for the whole run (population generation AND
// measurement) — no `Math.random`, no wall-clock, no Set/Map iteration order
// dependency (population is a plain array, indexed).
// ============================================================================

import type { AllelePair, GenomeV2, GenomeV2LocusKey } from './geneticsV2';
import { breedV2 } from './mutationV2';
import type { RarityTierV2 } from './rarityV2';
import { mulberry32 } from './rng';
import type { RngFn } from './rng';

/** Fixed seed for the whole calibration run — population generation and
 * measurement both derive from the ONE stream this produces. Changing this
 * value would change the exact measured counts; it is pinned here (not
 * re-derived per call) specifically so the test's assertion is reproducible
 * byte-for-byte across machines/runs, per the owner's explicit requirement. */
export const RARITY_CALIBRATION_SEED = 20260829;

/** Base population size (contract §4.5.7 point 1) — matches the docs-only
 * §4.5.5 simulation's own population size, carried over unchanged. */
const BASE_POPULATION_SIZE = 4000;
/** Three burn-in generations of 2000 intra-population breeds each. */
const BURN_IN_GENERATIONS = 3;
const BURN_IN_BREEDS_PER_GENERATION = 2000;
/** The measured sample size the owner specified — exactly 100000. */
export const RARITY_CALIBRATION_MEASURED_COUNT = 100_000;

function weightedPick<T extends string>(pool: readonly (readonly [T, number])[], rng: RngFn): T {
  const total = pool.reduce((sum, [, weight]) => sum + weight, 0);
  let draw = rng() * total;
  for (const [value, weight] of pool) {
    draw -= weight;
    if (draw < 0) return value;
  }
  // Floating-point edge case (draw lands exactly on the total) — last entry.
  return pool[pool.length - 1][0];
}

