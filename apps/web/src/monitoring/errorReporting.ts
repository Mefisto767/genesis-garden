// ============================================================================
// Этап 9 — необязательный адаптер отчётов об ошибках (Sentry). Честная
// оговорка: у проекта нет живого Sentry-аккаунта/DSN на момент написания —
// без VITE_SENTRY_DSN эта функция ничего не делает и НИЧЕГО не подгружает
// (динамический import — @sentry/browser не попадает в бандл вовсе, если
// ключ пуст). Как только владелец заведёт DSN (см. .env.example), реальный
// SDK инициализируется по-настоящему — это не заглушка "как будто работает".
// ============================================================================

export function installErrorReporting(): void {
  const dsn = import.meta.env.VITE_SENTRY_DSN as string | undefined;
  if (!dsn) return;

  import('@sentry/browser')
    .then(({ init }) => {
      init({
        dsn,
        environment: import.meta.env.MODE,
        // Низкий sample rate по умолчанию — бета маленькая, не нужно
        // отправлять трассировки на каждое взаимодействие.
        tracesSampleRate: 0.1,
      });
    })
    .catch(() => {
      // Сеть/пакет недоступны — молча продолжаем без отчётности об
      // ошибках, это не должно ронять игру.
    });
}
